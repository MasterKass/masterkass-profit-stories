export function DataPathDoc({ name, onClose }: { name: string | null; onClose: () => void }) {
  const doc = name ? OWNER_DOCS[name] : undefined;
  const open = !!doc;
  const onOpenChange = (v: boolean) => { if (!v) onClose(); };
  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="max-h-[85vh] max-w-2xl overflow-y-auto rounded-2xl">
        <DialogHeader>
          <DialogTitle className="text-left text-2xl tracking-[-0.03em]">{doc?.title}</DialogTitle>
          <DialogDescription className="text-left">
            {doc?.meta}
          </DialogDescription>
        </DialogHeader>
        <div className="space-y-6">
          {(doc?.sections ?? []).map((s) => (
            <section key={s.n}>
              <h3 className="text-base font-semibold">{s.n}</h3>
              <ul className="mt-2 list-disc space-y-1.5 pl-5 text-sm leading-relaxed text-muted-foreground">
                {s.items.map((i) => <li key={i}>{i}</li>)}
              </ul>
            </section>
          ))}
        </div>
      </DialogContent>
    </Dialog>
  );
}
