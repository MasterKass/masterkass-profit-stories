/** 1 000 -> «1 000» с неразрывным пробелом, чтобы число не разрывалось в карточке */
export function unitsLabel(n: number): string {
  return n
    .toLocaleString("ru-RU")
    .replace(/[\u00A0\u202F\s]/g, "\u00A0");
}
